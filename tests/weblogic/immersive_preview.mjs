// PIANO-IMMERSIVE-UI: LOCAL MOCK preview server for the Owner's visual
// review. Serves the REAL candidate UI (src/piano_core/web/static) with a
// small loopback mock Core whose playback position genuinely advances, so
// the Falling scene animates and the transport behaves end-to-end.
//
// THIS IS A FUNCTIONAL UI MOCK: it is NOT the real Pi, NOT the real piano,
// and NOT the real LED hardware. It exists so the Owner can try the
// composition (phone/tablet/desktop) before any acceptance decision.
//
// Usage: node tests/weblogic/immersive_preview.mjs [port]   (default 8901)
// Open: http://<this-host>:8901/ui/#/player   (Falling is the default view)
import { createServer } from "node:http";
import { readFile } from "node:fs/promises";
import { extname, join, resolve } from "node:path";

const PORT = Number(process.argv[2] || 8901);
const STATIC = resolve(import.meta.dirname, "../../src/piano_core/web/static");

// Committed fixture generated by the unchanged canonical Python pipeline.
const fixture = JSON.parse(await readFile(new URL("./fixtures/immersive_demo.json", import.meta.url)));
const fixtures = [fixture, ...JSON.parse(await readFile(new URL("./fixtures/player_library_demo.json", import.meta.url)))];
const songs = fixtures.map(({score}) => ({ song_id: score.song_id, filename: score.title.toLowerCase().replaceAll(" ", "-") + ".mid", relpath: score.title + ".mid", extension: ".mid", size_bytes: 1234, status: "parsed", midi_format: 1, track_count: 1, ticks_per_beat: 480, duration_seconds: score.duration_seconds, tempo_bpm_first: 80, title: score.title, indexed_at_utc: "2026-10-03T00:00:00Z" }));
const scoreFor = (id) => fixtures.find(f => f.score.song_id === id)?.score ?? null;

let seq = 100;
let playback = { available: true, state: "IDLE", song_id: null, title: null, position_seconds: 0, duration_seconds: 0, tempo_multiplier: 1, events_sent: 0, error: null };
let learning = { available: true, state: "IDLE", song_id: null, title: null, step_index: null, total_steps: null, completed_steps: 0, incorrect_attempts: 0, progress: 0, started_at: null, ended_at: null, error: null, midi_connection: "CONNECTED", session_id: null, mode: "WAIT_FOR_NOTE", hand_selection: null, section: null, target_tempo: null, accepted_notes: [], latest_outcome: "NONE", generation: 0, version: 0, updated_at: null, target: null, repetition: { current: 0, required: 1, successful: 0, failed: 0 } };
let led = { configured: true, enabled: true, available: true, connection: "CONNECTED", mode: "all", brightness: 80, active_note_count: 0, practice_active: false, last_error: null, transport: { host: "0.0.0.0", port: 8787 }, dropped_events: 0, frames_sent: 0 };

// The preview's playback clock: the position genuinely advances while
// PLAYING so the Falling scene animates like the real Player.
const startedAt = new Map();
setInterval(() => {
  if (playback.state === "PLAYING") {
    const t0 = startedAt.get("t") ?? Date.now();
    startedAt.set("t", t0);
    playback.position_seconds = Math.min((Date.now() - t0) / 1000, playback.duration_seconds);
    if (playback.position_seconds >= playback.duration_seconds) {
      playback = { ...playback, state: "IDLE", song_id: null, title: null, position_seconds: 0, events_sent: 0 };
    }
  }
  // Same fixture clock drives the mock live-note stream; the Piano view
  // consumes the existing contract, never decorative or physical input.
  const event = `event: snapshot\ndata: ${JSON.stringify(live())}\n\n`;
  for (const client of sseClients) client.write(event);
}, 250);

function json(res, value, status = 200) {
  const body = JSON.stringify(value);
  res.writeHead(status, { "content-type": "application/json", "content-length": Buffer.byteLength(body), "cache-control": "no-store" });
  res.end(body);
}
const readBody = async (req) => { let b = ""; for await (const c of req) b += c; return JSON.parse(b || "{}"); };

const sseClients = new Set();
const live = () => {
  seq += 1;
  const active = playback.state === "PLAYING" ? (scoreFor(playback.song_id)?.notes ?? []).filter(note =>
    note.onset_seconds <= playback.position_seconds &&
    playback.position_seconds < note.onset_seconds + note.duration_seconds) : [];
  return { schema_version: 1, runtime_epoch: "preview", sequence: seq,
    physical: { notes: [], outside_keyboard_count: 0, sustain: { value: 0, pressed: false }, midi_connection: "CONNECTED", revision: seq },
    playback: { available: true, notes: [...new Set(active.map(note => note.midi))].sort((a,b) => a-b),
      voices: active.map(note => ({ channel: note.channel, note: note.midi })), outside_keyboard_count: 0, sustain_channels: [] } };
};

const server = createServer(async (req, res) => {
  const url = new URL(req.url, "http://127.0.0.1");
  if (req.method === "POST" && url.pathname === "/api/v1/playback/play") {
    if (learning.state === "WAITING") { json(res, { error: { code: "activity_conflict", message: "Practice is active" } }, 409); return; }
    const body = await readBody(req);
    const song = songs.find((s) => s.song_id === body.song_id);
    if (!song) { json(res, { error: { code: "song_not_found", message: "Unknown demo song" } }, 404); return; }
    playback = { ...playback, state: "PLAYING", song_id: song.song_id, title: song.title, duration_seconds: song.duration_seconds, position_seconds: 0, events_sent: 4 };
    startedAt.set("t", Date.now());
    json(res, playback);
    return;
  }
  if (req.method === "POST" && url.pathname === "/api/v1/playback/pause") { playback = { ...playback, state: "PAUSED" }; json(res, playback); return; }
  if (req.method === "POST" && url.pathname === "/api/v1/playback/resume") { playback = { ...playback, state: "PLAYING" }; startedAt.set("t", Date.now() - playback.position_seconds * 1000); json(res, playback); return; }
  if (req.method === "POST" && url.pathname === "/api/v1/playback/stop") { playback = { ...playback, state: "IDLE", song_id: null, title: null, position_seconds: 0, events_sent: 0 }; json(res, { ...playback, stopped: true }); return; }
  if (req.method === "POST" && url.pathname === "/api/v1/learning/start") {
    if (["PLAYING", "PAUSED"].includes(playback.state)) { json(res, { error: { code: "activity_conflict", message: "Playback is active" } }, 409); return; }
    const body = await readBody(req);
    const song = songs.find((s) => s.song_id === body.song_id);
    if (!song) { json(res, { error: { code: "song_not_found", message: "Unknown demo song" } }, 404); return; }
    learning = { ...learning, state: "WAITING", song_id: song.song_id, title: song.title, step_index: 0, total_steps: scoreFor(song.song_id).notes.length, completed_steps: 0, progress: 0, session_id: `preview-${Date.now()}`, version: learning.version + 1, generation: learning.generation + 1, target: { notes: [scoreFor(song.song_id).notes[0].midi], names: ["C4"], chord: false, onset_seconds: scoreFor(song.song_id).notes[0].onset_seconds, target_id: "t:0" }, started_at: "t", updated_at: "t" };
    json(res, learning);
    return;
  }
  if (req.method === "POST" && url.pathname === "/api/v1/learning/stop") { learning = { ...learning, state: "IDLE", song_id: null, title: null, session_id: null, target: null, version: learning.version + 1 }; json(res, learning); return; }
  if (req.method === "PUT" && url.pathname === "/api/v1/led") {
    const body = await readBody(req);
    if (body.enabled !== undefined) led.enabled = body.enabled;
    if (body.mode !== undefined) led.mode = body.mode;
    if (body.brightness !== undefined) led.brightness = body.brightness;
    led.available = led.enabled;
    json(res, led);
    return;
  }
  if (req.method === "POST" && url.pathname === "/api/v1/led/clear") { json(res, led); return; }
  if (url.pathname.startsWith("/ui/")) {
    const name = url.pathname.slice(4) || "index.html";
    const path = join(STATIC, name);
    if (!path.startsWith(STATIC)) { res.writeHead(404).end(); return; }
    try {
      let body = await readFile(path);
      if (name === "index.html") body = Buffer.from(body.toString().replace('<div class="app-frame">', '<div class="app-frame"><p class="demo-banner">LOCAL DEMO / MOCK · No hardware</p>'));
      const types = { ".html": "text/html", ".js": "text/javascript", ".css": "text/css", ".svg": "image/svg+xml", ".webmanifest": "application/manifest+json", ".glb": "model/gltf-binary" };
      res.writeHead(200, { "content-type": types[extname(path)] || "application/octet-stream", "cache-control": "no-store" });
      res.end(body);
    } catch { res.writeHead(404).end(); }
    return;
  }
  if (url.pathname === "/" || url.pathname === "/ui") { res.writeHead(200, { "content-type": "text/html" }); res.end("<!DOCTYPE html><html><head><meta http-equiv='refresh' content='0;url=/ui/'></head><body><p>IMMERSIVE UI PREVIEW (LOCAL MOCK) — opening <a href='/ui/'>/ui/</a></p></body>"); return; }
  if (url.pathname === "/api/v1/device") { json(res, { product: "Piano Core (preview mock)", device_id: "00000000-0000-4000-8000-000000000000", display_code: "PC-PREVIEW", identity_schema: "piano-core-identity-v1" }); return; }
  if (url.pathname === "/api/v1/health") { json(res, { status: "ok", application: { state: "READY", since: "preview" }, midi_input: { connection: "CONNECTED" }, library: { ready: true, entries: songs.length }, playback }); return; }
  if (url.pathname === "/api/v1/state") { json(res, { schema_version: 1, midi_connection: "CONNECTED", sustain: { pressed: false, value: 0 }, pressed_notes: [], last_input: null, revision: seq }); return; }
  if (url.pathname === "/api/v1/led") { json(res, led); return; }
  if (url.pathname === "/api/v1/learning" || url.pathname === "/api/v1/practice") { json(res, learning); return; }
  if (url.pathname === "/api/v1/playback") { json(res, playback); return; }
  if (url.pathname === "/api/v1/live-notes") { json(res, live()); return; }
  if (url.pathname === "/api/v1/live-notes/stream") {
    res.writeHead(200, { "content-type": "text/event-stream", "cache-control": "no-cache", connection: "close" });
    res.write(`event: snapshot\ndata: ${JSON.stringify(live())}\n\n`);
    sseClients.add(res);
    const hb = setInterval(() => { try { res.write(`: heartbeat\n\n`); } catch {} }, 2000);
    req.on("close", () => { clearInterval(hb); sseClients.delete(res); });
    return;
  }
  if (url.pathname === "/api/v1/library/songs") {
    const q = url.searchParams.get("q");
    const list = q ? songs.filter((s) => s.filename.toLowerCase().includes(q.toLowerCase()) || (s.title || "").toLowerCase().includes(q.toLowerCase())) : songs;
    json(res, { query: { q }, count: list.length, songs: list });
    return;
  }
  const songMatch = url.pathname.match(/^\/api\/v1\/library\/songs\/(.+)$/);
  if (songMatch) { const s = songs.find((x) => x.song_id === songMatch[1]); if (s) { json(res, s); return; } res.writeHead(404).end(); return; }
  const scoreMatch = url.pathname.match(/^\/api\/v1\/score\/(.+)$/);
  if (scoreMatch) { json(res, scoreFor(scoreMatch[1])); return; }
  const plan = fixtures.find(f => url.pathname === `/api/v1/fingering/${f.score.song_id}`);
  if (plan) { json(res, plan.fingering); return; }
  if (req.method === "POST" && ["/api/v1/learning/restart-target", "/api/v1/learning/restart-section"].includes(url.pathname)) {
    learning = { ...learning, accepted_notes: [], version: learning.version + 1 };
    json(res, learning); return;
  }
  json(res, { error: { code: "not_found", message: "nf" } }, 404);
});

server.listen(PORT, "0.0.0.0", () => {
  console.log(`IMMERSIVE UI PREVIEW (LOCAL MOCK) — http://0.0.0.0:${server.address().port}/ui/`);
  console.log("This serves the REAL candidate UI with a FUNCTIONAL MOCK Core.");
  console.log("It is NOT the real Pi, piano, or LED hardware.");
});
